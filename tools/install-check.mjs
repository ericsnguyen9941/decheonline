// Install check: reads AOE1_DIR (never modified), lists the files the project
// needs with size and SHA-256, detects exe and dat versions, writes the
// hash-only docs/install-manifest.md. Exits 1 naming any missing file.
import { createHash } from 'node:crypto';
import { createReadStream } from 'node:fs';
import { readdir, readFile, stat, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { inflateRawSync } from 'node:zlib';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const manifestPath = join(root, 'docs', 'install-manifest.md');

// Plan Deliverable 4. Paths are looked up case-insensitively (Windows installs).
const required = [
  'data2/empires.dat',
  'data/graphics.drs', 'data2/graphics.drs',
  'data/Interfac.drs', 'data2/Interfac.drs',
  'data/sounds.drs', 'data2/sounds.drs',
  'data/Terrain.drs', 'data/Border.drs',
  'data2/TileEdge.dat',
  'language.dll', 'languagex.dll',
  'Empiresx.exe',
];
// Not in every install (the base exe is absent from some repacks): listed when present.
const optional = ['Empires.exe', 'data/Empires.dat'];

const dir = process.env.AOE1_DIR;
if (!dir) {
  console.error('assets:verify: set AOE1_DIR to the AoE1 + Rise of Rome install folder');
  process.exit(1);
}

const lowerCache = new Map();
async function resolveCaseInsensitive(rel) {
  let current = dir;
  for (const part of rel.split('/')) {
    let names = lowerCache.get(current);
    if (!names) {
      names = await readdir(current).catch(() => []);
      lowerCache.set(current, names);
    }
    const hit = names.find((n) => n.toLowerCase() === part.toLowerCase());
    if (!hit) return null;
    current = join(current, hit);
  }
  return current;
}

function sha256(path) {
  return new Promise((resolve, reject) => {
    const hash = createHash('sha256');
    createReadStream(path).on('data', (c) => hash.update(c)).on('error', reject).on('end', () => resolve(hash.digest('hex')));
  });
}

// VS_FIXEDFILEINFO file version, found by its signature after the UTF-16 key.
function peFileVersion(buf) {
  const key = Buffer.from('VS_VERSION_INFO', 'utf16le');
  const at = buf.indexOf(key);
  if (at < 0) return null;
  const sig = Buffer.from([0xbd, 0x04, 0xef, 0xfe]);
  const fixed = buf.indexOf(sig, at);
  if (fixed < 0 || fixed - at > 128) return null;
  const ms = buf.readUInt32LE(fixed + 8);
  const ls = buf.readUInt32LE(fixed + 12);
  return `${ms >>> 16}.${ms & 0xffff}.${ls >>> 16}.${ls & 0xffff}`;
}

// The 1.0a/1.0b/1.0c strings appear in the exe's patch-level table.
function patchStrings(buf) {
  const text = buf.toString('latin1');
  return ['1.0a', '1.0b', '1.0c'].filter((s) => text.includes(`\0${s}\0`));
}

async function datVersion(path) {
  try {
    return inflateRawSync(await readFile(path)).subarray(0, 8).toString('latin1').replace(/\0+$/, '');
  } catch {
    return null;
  }
}

const rows = [];
const missing = [];
for (const rel of required) {
  const path = await resolveCaseInsensitive(rel);
  if (!path) { missing.push(rel); continue; }
  rows.push({ rel, path, size: (await stat(path)).size, hash: await sha256(path), optional: false });
}
for (const rel of optional) {
  const path = await resolveCaseInsensitive(rel);
  if (path) rows.push({ rel, path, size: (await stat(path)).size, hash: await sha256(path), optional: true });
}
const soundDir = await resolveCaseInsensitive('sound');
const soundFiles = soundDir ? (await readdir(soundDir)).filter((n) => /\.(wav|mid)$/i.test(n)) : [];
if (soundFiles.length === 0) missing.push('sound/ (music files)');

if (missing.length > 0) {
  console.error(`assets:verify: ${dir} is incomplete; missing:`);
  for (const rel of missing) console.error(`  ${rel}`);
  process.exit(1);
}

const exe = rows.find((r) => r.rel === 'Empiresx.exe');
const exeBuf = await readFile(exe.path);
const exeVersion = peFileVersion(exeBuf);
const patches = patchStrings(exeBuf);
const ror = rows.find((r) => r.rel === 'data2/empires.dat');
const rorDat = await datVersion(ror.path);
const baseRow = rows.find((r) => r.rel === 'data/Empires.dat');
const baseDat = baseRow ? await datVersion(baseRow.path) : null;

// RoR exe (Empiresx.exe) loading data2/empires.dat (genie dat "VER 3.7") with the
// patch-level table up to 1.0c. A modified exe cannot be told from retail by
// content alone, so the hash is reported for comparison, not judged.
const looksRor = exe.size > 0 && rorDat === 'VER 3.7' && patches.includes('1.0a');
const verdict = looksRor ? 'RoR 1.0a' : 'unrecognised version';

const lines = [
  '# Install manifest',
  '',
  'Generated by `npm run assets:verify`. Hashes only; no game content.',
  '',
  `- Detected: **${verdict}**`,
  `- Empiresx.exe: PE file version ${exeVersion ?? 'none'}, patch-level strings ${patches.join(', ') || 'none'}`,
  `- data2/empires.dat: ${rorDat ?? 'unreadable'}${baseDat ? `; data/Empires.dat: ${baseDat}` : ''}`,
  `- sound/: ${soundFiles.length} audio files`,
  '',
  '| file | size | sha256 |',
  '| --- | ---: | --- |',
  ...rows.map((r) => `| ${r.rel}${r.optional ? ' (optional)' : ''} | ${r.size} | ${r.hash} |`),
  '',
];
await writeFile(manifestPath, lines.join('\n'));

for (const r of rows) console.log(`${r.rel}  ${r.size}  ${r.hash}`);
console.log(`Empiresx.exe PE file version: ${exeVersion ?? 'none'}; patch strings: ${patches.join(', ') || 'none'}`);
console.log(`dat: ${rorDat ?? 'unreadable'}`);
console.log(`Detected: ${verdict}`);
console.log(`Wrote ${manifestPath}`);
process.exit(looksRor ? 0 : 1);
